package dev.materione.pack.compile;

import dev.materione.api.content.EffectSpec;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Locale;

/**
 * Composes the injected text-shader set from the pack's compiled text
 * effects (runtime-systems §6): one version-matched <em>overlay</em> per
 * shader-format rung, each carrying the pack's replacement
 * {@code rendertype_text} vertex shader plus a generated
 * {@code materione_text_effects.glsl} include with one branch per effect.
 *
 * <p>Only the vertex shader is replaced — the replacement outputs the
 * vanilla varyings, so the client's own fragment shader (alpha cutout,
 * fog) keeps working unmodified. Shader files never ship in the base
 * layer: a client whose format matches no rung receives a shader-free
 * pack (Nexo's overlay strategy).
 *
 * <p>The include detects effect text by its <strong>signal color</strong>
 * ({@link EffectSpec#signalRgb()} — the color the runtime paints the span
 * with) and applies the baked animation: displacement runs in the vertex
 * stage pre-transform (wave, shake), recoloring post-lightmap (rainbow,
 * pulse). Time comes from the {@code GameTime} shader global (a declared
 * uniform on pre-1.21.6 rungs, the Globals UBO since).
 */
final class TextEffectShaders {

    /** One version rung: overlay directory, template variant, shipped shader name, format range. */
    record Rung(
            String overlayDir, String variantDir, String shaderName,
            int minFormat, int maxFormat, int bakeFormat, boolean shipJson) {}

    /** The verified ladder — formats follow the pack's advertising range (46..88). */
    static final List<Rung> RUNGS = List.of(
            new Rung("materione_1_21_4", "v1_21_4", "rendertype_text", 46, 62, 46, true),
            new Rung("materione_1_21_6", "v1_21_6", "rendertype_text", 63, 83, 63, true),
            new Rung("materione_26_1", "v26_1", "rendertype_text", 84, 87, 84, false),
            new Rung("materione_26_2", "v26_2", "text", 88, 999, 88, true));

    private static final String INCLUDE_PATH = "assets/minecraft/shaders/include/materione_text_effects.glsl";

    private TextEffectShaders() {}

    /** True when the given client resource format is covered by the ladder. */
    static boolean covers(int resourceFormat) {
        return RUNGS.stream().anyMatch(rung ->
                resourceFormat >= rung.minFormat() && resourceFormat <= rung.maxFormat());
    }

    /** The shader names the ladder overrides (for Sodium's ignored_shaders). */
    static List<String> overriddenShaders() {
        return RUNGS.stream().map(Rung::shaderName).distinct().toList();
    }

    /**
     * Builds the generated include: one pre-transform branch (wave/shake)
     * and one post-transform branch (rainbow/pulse) per effect, parameters
     * baked as GLSL constants.
     */
    static String include(List<EffectSpec> effects, int bakeFormat) {
        var out = new StringBuilder();
        out.append("// Generated by Materione from the pack's effects/*.yml — do not edit.\n");
        out.append("// One branch per effect, keyed on the span's signal color.\n");
        out.append("#define MATERIONE_PACK_FORMAT ").append(bakeFormat).append('\n');
        out.append("""
                #if MATERIONE_PACK_FORMAT < 63
                uniform float GameTime; // declared by the program json pre-1.21.6
                #endif

                // GameTime is ticks/24000 — 1200 units per real second
                #define MTR_SECONDS (GameTime * 1200.0)
                #define MTR_TAU 6.28318530718

                bool mtrSignal(vec3 color, vec3 signal) {
                    return distance(color, signal) < 0.002;
                }

                float mtrHash(float n) {
                    return fract(sin(n) * 43758.5453123);
                }

                // GLSL forbids assigning to an attribute, so both hooks
                // operate on the caller's local copy of the position
                void materionePreTransform(inout vec3 pos) {
                """);
        for (EffectSpec effect : effects) {
            String signal = signalVec(effect);
            switch (effect.kind()) {
                case "wave" -> out.append(String.format(Locale.ROOT, """
                            if (mtrSignal(Color.rgb, %s)) {
                                pos.y += sin(MTR_SECONDS * %s * MTR_TAU + pos.x * 0.8) * %s;
                            }
                    """, signal, glsl(effect.speed()), glsl(effect.amplitude())));
                case "shake" -> out.append(String.format(Locale.ROOT, """
                            if (mtrSignal(Color.rgb, %s)) {
                                float phase = floor(MTR_SECONDS * %s * 20.0);
                                pos.x += (mtrHash(phase) - 0.5) * 1.5 * %s;
                                pos.y += (mtrHash(phase + 91.7) - 0.5) * 1.5 * %s;
                            }
                    """, signal, glsl(effect.speed()), glsl(effect.amplitude()), glsl(effect.amplitude())));
                default -> { /* rainbow/pulse are post-transform */ }
            }
        }
        out.append("}\n\nvoid materionePostTransform(in vec3 pos) {\n");
        for (EffectSpec effect : effects) {
            String signal = signalVec(effect);
            switch (effect.kind()) {
                case "rainbow" -> out.append(String.format(Locale.ROOT, """
                            if (mtrSignal(Color.rgb, %s)) {
                                %s
                            }
                    """, signal, rainbowBody(effect)));
                case "pulse" -> out.append(String.format(Locale.ROOT, """
                            if (mtrSignal(Color.rgb, %s)) {
                                vertexColor.rgb *= 1.0 + %s * 0.35 * sin(MTR_SECONDS * %s * MTR_TAU);
                            }
                    """, signal, glsl(effect.amplitude()), glsl(effect.speed())));
                default -> { /* wave/shake are pre-transform */ }
            }
        }
        out.append("}\n");
        return out.toString();
    }

    /** Hue cycling, or an inlined right-associative ternary chain over the authored color stops. */
    private static String rainbowBody(EffectSpec effect) {
        float phase = effect.speed() * 0.25f;
        float spread = effect.amplitude() * 0.1f;
        if (effect.colors().size() >= 2) {
            int count = effect.colors().size();
            var chain = new StringBuilder();
            chain.append("vertexColor.rgb = ");
            for (int i = 0; i < count; i++) {
                String from = glslColor(effect.colors().get(i));
                String to = glslColor(effect.colors().get((i + 1) % count));
                double lo = (double) i / count;
                double hi = (double) (i + 1) / count;
                String mix = "mix(" + from + ", " + to + ", (mt - " + glsl(lo)
                        + ") * " + glsl(count) + ")";
                if (i == count - 1) {
                    // the last stop wraps to the first: the trailing else
                    chain.append(mix);
                } else {
                    chain.append("(mt < ").append(glsl(hi)).append(" ? ").append(mix).append(" : ");
                }
            }
            chain.append(")".repeat(Math.max(0, count - 1))).append(";");
            return "float mt = fract(MTR_SECONDS * " + glsl(phase) + " + pos.x * "
                    + glsl(spread) + ");\n        " + chain;
        }
        // cosine-palette rainbow: three phase-shifted cosines
        return String.format(Locale.ROOT,
                "vertexColor.rgb = 0.5 + 0.5 * cos(MTR_TAU * (MTR_SECONDS * %s * 0.1 + pos.x * %s * 0.05) + vec3(0.0, 2.094, 4.188));",
                glsl(effect.speed()), glsl(effect.amplitude()));
    }

    private static String signalVec(EffectSpec effect) {
        float blue = ((effect.signalRgb() & 0xFF) & 0xFF) / 255.0f;
        return String.format(Locale.ROOT, "vec3(1.0, 0.0, %.8f)", blue);
    }

    private static String glslColor(String hex) {
        String clean = hex.replace("#", "");
        int rgb = Integer.parseInt(clean, 16);
        return String.format(Locale.ROOT, "vec3(%.8f, %.8f, %.8f)",
                ((rgb >> 16) & 0xFF) / 255.0, ((rgb >> 8) & 0xFF) / 255.0, (rgb & 0xFF) / 255.0);
    }

    private static String glsl(float value) {
        return String.format(Locale.ROOT, "%.6f", value);
    }

    private static String glsl(double value) {
        return glsl((float) value);
    }

    /** Reads a bundled wrapper template. */
    static String template(String variantDir, String fileName) {
        String resource = "/shaders/" + variantDir + "/" + fileName;
        try (InputStream in = TextEffectShaders.class.getResourceAsStream(resource)) {
            if (in == null) {
                throw new IllegalStateException("missing bundled shader template " + resource);
            }
            return new String(in.readAllBytes(), StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new IllegalStateException("could not read bundled shader template " + resource, e);
        }
    }

    /** The generated include path inside every overlay. */
    static String includePath() {
        return INCLUDE_PATH;
    }
}
