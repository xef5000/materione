package dev.materione.buildlogic

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Generates `dev/materione/plugin/MaterioneVersion.java` with the project
 * version as a compile-time constant. Deliberately timestamp-free (D7
 * reproducibility).
 */
abstract class GenerateVersionSourceTask : DefaultTask() {

    @get:Input
    abstract val version: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val dir = outputDir.get().file("dev/materione/plugin").asFile.apply { mkdirs() }
        dir.resolve("MaterioneVersion.java").writeText(
            """
            // Generated by GenerateVersionSourceTask — do not edit.
            package dev.materione.plugin;

            public final class MaterioneVersion {
                private MaterioneVersion() {}

                public static final String VERSION = "${version.get()}";
            }
            """.trimIndent() + "\n",
        )
    }
}
