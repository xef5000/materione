import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import java.util.zip.CRC32;
import java.util.zip.Deflater;

/**
 * Generates fixtures/packs/corpus — the M1 exit-criteria pack (exactly 50
 * items). Deterministic: same program, same bytes. Run directly:
 *
 * <pre>java fixtures/tools/GenerateCorpus.java</pre>
 *
 * The corpus is grow-only once committed (fixtures/README.md); regeneration
 * is for review, not for CI.
 *
 * <p>Item mix (why each family exists):
 * <ul>
 *   <li>8 gems + 8 amulets + 8 rings + 6 blocks = 30 auto-model items
 *       (texture → generated model → item definition: the full pack path;
 *       several items deliberately SHARE one texture)</li>
 *   <li>10 charms — template inheritance (corpus_base), material-only output</li>
 *   <li>10 scrolls — material-only items (display/lore, no pack output)</li>
 * </ul>
 */
public class GenerateCorpus {

    static final Path ROOT = Path.of("fixtures/packs/corpus");

    static final List<String> COLORS =
            List.of("red", "blue", "green", "yellow", "violet", "white", "black", "pink");
    static final List<String> BLOCK_MATERIALS = List.of(
            "REDSTONE_BLOCK", "LAPIS_BLOCK", "EMERALD_BLOCK", "GOLD_BLOCK", "DIAMOND_BLOCK", "COAL_BLOCK");
    static final List<String> GEM_MATERIALS =
            List.of("QUARTZ", "AMETHYST_SHARD", "EMERALD", "DIAMOND");
    static final List<String> CHARM_MATERIALS = List.of(
            "BONE", "SUGAR", "STRING", "LEATHER", "PAPER", "BOOK", "SLIME_BALL", "SNOWBALL", "EGG", "GLOWSTONE_DUST");
    static final List<String> CHARM_NAMES =
            List.of("lucky", "swift", "sturdy", "glossy", "quiet", "loud", "warm", "cool", "crisp", "dull");

    /** (r, g, b) per color — fixed, no randomness anywhere in this program. */
    static final Map<String, int[]> TINTS = Map.of(
            "red", new int[] {196, 40, 48}, "blue", new int[] {44, 84, 168},
            "green", new int[] {64, 148, 60}, "yellow", new int[] {222, 190, 50},
            "violet", new int[] {136, 62, 168}, "white", new int[] {228, 228, 228},
            "black", new int[] {44, 42, 48}, "pink", new int[] {226, 122, 172});

    public static void main(String[] args) throws IOException {
        write("pack.yml", """
                # The corpus fixture pack (M1 exit criteria): exactly 50 items, generated by
                # fixtures/tools/GenerateCorpus.java and committed verbatim. Grow-only.
                id: corpus
                version: 1.0.0
                schema_version: 1

                depends: []
                """);

        write("templates/base.yml", """
                # Inheritance base for the charm family.
                corpus_base:
                  material: PAPER
                  display_name: "Unnamed Charm"
                """);

        for (String color : COLORS) {
            write("items/gem_" + color + ".yml", """
                    gem_%s:
                      material: %s
                      texture: corpus/%s
                      display_name: "%s Gem"
                    """.formatted(color, GEM_MATERIALS.get(COLORS.indexOf(color) % GEM_MATERIALS.size()),
                    color, capitalize(color)));
        }
        for (String color : COLORS) {
            write("items/amulet_" + color + ".yml", """
                    amulet_%s:
                      material: GOLD_NUGGET
                      texture: corpus/%s
                      display_name: "%s Amulet"
                      lore:
                        - "Hums faintly"
                    """.formatted(color, color, capitalize(color)));
        }
        for (String color : COLORS) {
            write("items/ring_" + color + ".yml", """
                    ring_%s:
                      material: IRON_NUGGET
                      texture: corpus/%s
                      display_name: "%s Ring"
                    """.formatted(color, color, capitalize(color)));
        }
        for (int i = 0; i < 6; i++) {
            String color = COLORS.get(i);
            write("items/block_" + color + ".yml", """
                    block_%s:
                      material: %s
                      texture: corpus/%s
                      display_name: "%s Block"
                    """.formatted(color, BLOCK_MATERIALS.get(i), color, capitalize(color)));
        }

        for (int i = 0; i < CHARM_NAMES.size(); i++) {
            String name = CHARM_NAMES.get(i);
            write("items/charm_" + name + ".yml", """
                    charm_%s:
                      template: corpus_base
                      material: %s
                      display_name: "%s Charm"
                    """.formatted(name, CHARM_MATERIALS.get(i), capitalize(name)));
        }
        for (int i = 1; i <= 10; i++) {
            write("items/scroll_%02d.yml".formatted(i), """
                    scroll_%02d:
                      material: BOOK
                      display_name: "Scroll %02d"
                      lore:
                        - "Written in a steady hand"
                        - "Sealed with wax"
                    """.formatted(i, i));
        }

        write("recipes/ring_red.yml", """
                ring_red:
                  type: shaped
                  result: ring_red
                  shape:
                    - " R "
                    - "R R"
                    - " R "
                  ingredients:
                    R: gem_red
                """);
        write("recipes/amulet_blue.yml", """
                amulet_blue:
                  type: shapeless
                  result: amulet_blue
                  ingredients:
                    - gem_blue
                    - gem_blue
                    - minecraft:gold_nugget
                """);
        write("recipes/gem_white_smelt.yml", """
                gem_white_smelt:
                  type: furnace
                  input: gem_white
                  result: gem_black
                  experience: 0.1
                  cookingtime: 100
                """);
        write("recipes/charm_lucky.yml", """
                charm_lucky:
                  type: shaped
                  result: charm_lucky
                  shape:
                    - " S "
                    - "SLS"
                    - " S "
                  ingredients:
                    S: minecraft:string
                    L: minecraft:leather
                """);

        for (String color : COLORS) {
            Path path = ROOT.resolve("assets/textures/corpus/" + color + ".png");
            Files.createDirectories(path.getParent());
            Files.write(path, gemTexture(color));
        }

        int items = 3 * COLORS.size() + 6 + CHARM_NAMES.size() + 10;
        System.out.println("corpus: " + items + " items, " + COLORS.size()
                + " textures, 4 recipes -> " + ROOT.toAbsolutePath());
    }

    // --- PNG -----------------------------------------------------------------

    /** 16x16 gem: light core, mid diamond rim, transparent corners. */
    static byte[] gemTexture(String color) {
        int[] tint = TINTS.get(color);
        int[] core = {bright(tint[0]), bright(tint[1]), bright(tint[2]), 255};
        int[] rim = {tint[0], tint[1], tint[2], 255};
        int[] transparent = {0, 0, 0, 0};
        byte[] raw = new byte[16 * (1 + 16 * 4)];
        int at = 0;
        for (int y = 0; y < 16; y++) {
            raw[at++] = 0; // filter type: none
            for (int x = 0; x < 16; x++) {
                int d = Math.abs(x - 7) + Math.abs(y - 7);
                int[] px = d <= 3 ? core : d <= 6 ? rim : transparent;
                raw[at++] = (byte) px[0];
                raw[at++] = (byte) px[1];
                raw[at++] = (byte) px[2];
                raw[at++] = (byte) px[3];
            }
        }
        return png(16, 16, raw);
    }

    /** Minimal deterministic PNG writer (RGBA, no interlace). */
    static byte[] png(int width, int height, byte[] raw) {
        var out = new ByteArrayOutputStream();
        out.writeBytes(new byte[] {(byte) 0x89, 'P', 'N', 'G', '\r', '\n', 0x1A, '\n'});
        chunk(out, "IHDR", ihdr(width, height));
        chunk(out, "IDAT", deflate(raw));
        chunk(out, "IEND", new byte[0]);
        return out.toByteArray();
    }

    static byte[] ihdr(int width, int height) {
        return new byte[] {
                (byte) (width >>> 24), (byte) (width >>> 16), (byte) (width >>> 8), (byte) width,
                (byte) (height >>> 24), (byte) (height >>> 16), (byte) (height >>> 8), (byte) height,
                8, 6, 0, 0, 0}; // 8-bit, RGBA
    }

    static byte[] deflate(byte[] data) {
        var deflater = new Deflater(9, true); // zlib container, no gzip header
        deflater.setInput(data);
        deflater.finish();
        var compressed = new ByteArrayOutputStream();
        byte[] buffer = new byte[4096];
        while (!deflater.finished()) {
            int n = deflater.deflate(buffer);
            compressed.write(buffer, 0, n);
        }
        deflater.end();
        return compressed.toByteArray();
    }

    static void chunk(ByteArrayOutputStream out, String kind, byte[] data) {
        out.writeBytes(int32(data.length));
        byte[] type = kind.getBytes(StandardCharsets.US_ASCII);
        out.writeBytes(type);
        out.writeBytes(data);
        var crc = new CRC32();
        crc.update(type);
        crc.update(data);
        out.writeBytes(int32((int) crc.getValue()));
    }

    static byte[] int32(int value) {
        return new byte[] {(byte) (value >>> 24), (byte) (value >>> 16), (byte) (value >>> 8), (byte) value};
    }

    // --- helpers -------------------------------------------------------------

    static void write(String rel, String text) throws IOException {
        Path path = ROOT.resolve(rel);
        Files.createDirectories(path.getParent());
        // LF unconditionally: fixture bytes are part of the lossless round-trip
        // contract and must not depend on the generating OS
        Files.writeString(path, text.stripTrailing() + "\n", StandardCharsets.UTF_8);
    }

    static int bright(int channel) {
        return Math.min(255, channel + 60);
    }

    static String capitalize(String text) {
        return Character.toUpperCase(text.charAt(0)) + text.substring(1);
    }
}
